from .contracts import ControlCommand
from .safety_policy import SensorObservation


class DrivingAgent(Protocol):
    def initialize(self, config: Mapping[str, Any]) -> None: ...
    def reset(self) -> None: ...
    def process_observation(self, observation: SensorObservation) -> None: ...
    def get_control(self) -> ControlCommand | None: ...
    def shutdown(self) -> None: ...
