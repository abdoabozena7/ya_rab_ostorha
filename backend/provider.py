"""Application boundary: no rendering or locally simulated vehicle state."""
from typing import Protocol
from .core.contracts import ControlCommand, SimulationFrame


class SimulationProvider(Protocol):
    name: str
    fixed_delta: float
    cleanup_errors: list[str]
    def connect(self): ...
    def disconnect(self): ...
    def is_connected(self) -> bool: ...
    def load_world(self, map_name: str): ...
    def reset_world(self): ...
    def spawn_ego_vehicle(self): ...
    def destroy_ego_vehicle(self): ...
    def set_throttle(self, value: float): ...
    def set_brake(self, value: float): ...
    def set_steering(self, value: float): ...
    def set_reverse(self, reverse: bool): ...
    def set_handbrake(self, enabled: bool): ...
    def set_controls(self, **controls): ...
    def apply_control(self, command: ControlCommand) -> None: ...
    def get_simulation_frame(self) -> SimulationFrame: ...
    def step(self): ...
    def get_vehicle_state(self) -> dict: ...
    def get_sensor_state(self) -> dict: ...
    def get_world_state(self) -> dict: ...
    def get_camera_frame(self): ...
    def reset_vehicle(self): ...
    def set_paused(self, paused: bool): ...
    def close(self): ...
